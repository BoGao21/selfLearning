/**
单例模式

1、确保一个类只有一个实例，并提供全局访问点。

2、实现要点：
（1）构造函数私有化：确保外部不能直接创建对象。
（2）禁用拷贝和赋值：避免通过拷贝或赋值创建新实例。
（3）提供全局访问点：通过静态成员函数获取唯一实例。
（4）线程安全：多线程环境下确保只创建一个实例。
（5）延迟初始化（可选）：有些场景下希望第一次使用时才创建实例（懒汉式），而有些场景下希望程序启动时就创建（饿汉式）。
（6）资源释放：一般情况下，单例对象在程序运行期间一直存在，不需要手动释放。如果使用new创建，可以考虑使用智能指针，或者使用静态成员变量（在程序结束时自动销毁）。使用局部静态变量方式可以自动销毁。

3、懒汉式（线程不安全）和饿汉式（线程安全），现代C++中推荐线程安全懒汉式（使用局部静态变量），示例代码即为局部静态变量的懒汉式。

**/

class Singleton 
{
private:
    Singleton() {}
    Singleton(const Singleton&) = delete;
    Singleton& operator=(const Singleton&) = delete;
 
public:
    static Singleton& getInstance() 
    {
        static Singleton instance; // 线程安全
        return instance;
    }
};
